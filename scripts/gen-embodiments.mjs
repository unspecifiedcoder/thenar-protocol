/** Emit the browser copy of the embodiment registry from the TypeScript one. */
import { writeFileSync } from "node:fs";
import { EMBODIMENTS } from "../packages/protocol/src/embodiments.ts";
const body = JSON.stringify(EMBODIMENTS, null, 2);
writeFileSync("apps/web/embodiments.js",
`/* embodiments.js — GENERATED by scripts/gen-embodiments.mjs. Do not edit.
 *
 * The browser copy of the registry. Generated rather than hand-kept so the
 * builder cannot offer a robot, a licence or a DoF count the exporter does not
 * have; \`embodiments.test.mjs\` fails if this drifts.
 */
export const EMBODIMENTS = ${body};

export const byId = (id) => EMBODIMENTS.find((e) => e.id === id);
export const byClass = (c) => EMBODIMENTS.filter((e) => e.class === c);
`);
console.log(`wrote apps/web/embodiments.js — ${EMBODIMENTS.length} models`);
